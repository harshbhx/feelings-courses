// Embeds migrations/*.sql into functions/_generated/migrations.ts, which functions/_lib/migrate.ts
// applies on the first request of each isolate (plan 1.15). Runs on `npm install` (postinstall),
// and before build, typecheck and tests. The output is gitignored.
//
//   node scripts/embed-migrations.mjs

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { loadMigrations } from "./lib/migrations.mjs";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "functions", "_generated");
const outFile = path.join(outDir, "migrations.ts");

const migrations = loadMigrations();
const body = `// GENERATED by scripts/embed-migrations.mjs from migrations/*.sql. Do not edit.
import type { Migration } from "../_lib/migrate.ts";

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

mkdirSync(outDir, { recursive: true });
// Only rewrite when something changed, so watchers and incremental type checks stay quiet.
if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== body) writeFileSync(outFile, body);
console.log(`embed-migrations: ${migrations.length} migration(s) → functions/_generated/migrations.ts`);
